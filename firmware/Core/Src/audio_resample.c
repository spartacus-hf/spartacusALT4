uint8_t AUDIO_Resample(audio_resample_t *s, const float input[3], float input_rate, float output[3])
{
    if (!isfinite(input_rate) || input_rate < 48000.0f || input_rate > 50000.0f) return 0U;
    s->index = (s->index + 1U) & 15U;
    for (unsigned ch = 0U; ch < 3U; ++ch) s->history[ch][s->index] = input[ch];
    s->phase += 48000.0f;
    if (s->phase < input_rate) return 0U;
    s->phase -= input_rate;
    unsigned phase = (unsigned)(s->phase * (32.0f / 48000.0f));
    if (phase > 31U) phase = 31U;
    for (unsigned ch = 0U; ch < 3U; ++ch) {
        float value = 0.0f;
        for (unsigned k = 0U; k < 16U; ++k)
            value += s->history[ch][(s->index - k) & 15U] * (float)audio_sinc_q15[phase][k];
        output[ch] = value * (1.0f / 32768.0f);
    }
    return 1U;
}
